/* One increment per Cordova build invocation, shared by all APKs from that build.
 * The counter persists in the project workspace; never reset it during builds.
 * Build numbers are diagnostics, not an app version or a session identifier. */
"use strict";
var fs = require("fs");
var path = require("path");
module.exports = function (context) {
  var root = context.opts.projectRoot;
  var counter = path.join(root, ".multicam-build-number");
  var output = path.join(root, "www", "js", "build-info.js");
  var previous = Number(fs.readFileSync(counter, "utf8").trim());
  if (!Number.isSafeInteger(previous) || previous < 0) throw new Error("Invalid MultiCam build counter");
  var next = previous + 1;
  fs.writeFileSync(counter, String(next) + "\n");
  fs.writeFileSync(output, "/* Generated by Cordova before_build. */\nwindow.MultiCamBuild = { number: " + next + " };\n");
  console.log("MULTICAM_BUILD_NUMBER=" + next);
};
